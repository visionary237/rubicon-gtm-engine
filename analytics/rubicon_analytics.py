#!/usr/bin/env python3
"""RUBICON Revenue Learning — SQL KPIs + guarded hypotheses (standard library only).

    python3 analytics/rubicon_analytics.py [outcomes.json] [--db outputs/analytics/rubicon.db]

Loads campaign outcomes into SQLite (sql/schema.sql), runs sql/kpis.sql, adds
Wilson confidence intervals, flags small samples, and PROPOSES experiments.
It never changes a scoring rule: rule changes are proposed, tested, then
validated by a human (see BUSINESS_RULES.md).
"""
from __future__ import annotations

import json
import math
import sqlite3
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MIN_SAMPLE = 30  # below this, a rate is reported but not interpreted


def wilson(successes: int, n: int, z: float = 1.96) -> tuple[float, float] | None:
    if n == 0:
        return None
    p = successes / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return round(max(0.0, c - h), 4), round(min(1.0, c + h), 4)


def load(db: sqlite3.Connection, outcomes_path: Path) -> int:
    db.executescript((ROOT / "sql" / "schema.sql").read_text(encoding="utf-8"))
    rows = json.loads(outcomes_path.read_text(encoding="utf-8"))["outcomes"]
    db.execute("DELETE FROM campaign_outcomes")
    db.executemany(
        "INSERT INTO campaign_outcomes VALUES (:accountId,:contactId,:offerId,:sector,:source,:repId,:calls,:connected,:conversation,"
        ":meetingBooked,:meetingHeld,:won,:wonAmountEUR,:objection,:lossReason,:enrichmentCostCents,:simulated)",
        [{**r, **{k: int(r[k]) for k in ("connected", "conversation", "meetingBooked", "meetingHeld", "won", "simulated")}} for r in rows],
    )
    db.commit()
    return len(rows)


def run_kpis(db: sqlite3.Connection) -> dict[str, list[dict]]:
    out, name, buf = {}, None, []
    for line in (ROOT / "sql" / "kpis.sql").read_text(encoding="utf-8").splitlines():
        if line.startswith("-- name:"):
            if name and "".join(buf).strip():
                out[name] = _q(db, "\n".join(buf))
            name, buf = line.split(":", 1)[1].strip(), []
        elif not line.startswith("--") or name:
            buf.append(line)
    if name:
        out[name] = _q(db, "\n".join(buf))
    return out


def _q(db: sqlite3.Connection, sql: str) -> list[dict]:
    cur = db.execute(sql)
    cols = [c[0] for c in cur.description]
    return [dict(zip(cols, r)) for r in cur.fetchall()]


def hypotheses(k: dict) -> list[dict]:
    """Turn observations into experiments to run — never into automatic rule changes."""
    hyps = []
    sectors = [s for s in k["by_sector"] if s["n"] >= MIN_SAMPLE]
    if len(sectors) >= 2:
        best, worst = sectors[0], sectors[-1]
        lo_b, _ = wilson(best["meetings"], best["n"])
        _, hi_w = wilson(worst["meetings"], worst["n"])
        hyps.append({
            "observation": f"{best['sector']} books {best['meetings_per_worked_account']:.1%} meetings per worked account vs {worst['sector']} {worst['meetings_per_worked_account']:.1%}.",
            "overlap": "intervals overlap: not distinguishable yet" if lo_b <= hi_w else "intervals do not overlap",
            "experiment": f"Run the next two batches with a 60/40 split toward {best['sector']} and compare meetings/worked account with the same script and rep allocation.",
            "rule_change": "none until the experiment is reviewed",
        })
    if k["objections"]:
        top = k["objections"][0]
        hyps.append({"observation": f"Most frequent objection: {top['objection']} ({top['n']}).",
                     "experiment": "Draft a two-sentence answer, A/B it across reps for two weeks, measure meetings/conversation.", "rule_change": "none"})
    hyps.append({"observation": "Correlation is not causation: sectors also differ by rep allocation, list source and timing.",
                 "experiment": "Hold rep and source constant when comparing verticals.", "rule_change": "none"})
    return hyps


def report(n: int, k: dict, hyps: list[dict], simulated: bool) -> str:
    f = k["funnel"][0]
    L = ["# RUBICON · Revenue Learning report", ""]
    if simulated:
        L += ["> ⚠️ **SIMULATED DATA.** These outcomes were generated by `scripts/generate-synthetic.cjs` from arbitrary hypotheses.",
              "> They demonstrate the analysis pipeline only and say nothing about real conversion rates or RUBICON performance.", ""]
    L += ["## Funnel (denominators explicit)", "", "| Metric | Value | Definition | 95% CI |", "|---|---|---|---|"]
    rows = [("Worked accounts", f["worked_accounts"], "accounts with ≥1 outbound call", None),
            ("Connect rate", f["connect_rate"], "connected / worked accounts", wilson(f["connected"], f["worked_accounts"])),
            ("Conversation rate", f["conversation_rate"], "conversations / connected", None),
            ("Meeting rate", f["meeting_rate"], "meetings booked / conversations", None),
            ("Show rate", f["show_rate"], "meetings held / meetings booked", None),
            ("Win rate", f["win_rate"], "won / meetings held", None),
            ("Won revenue (EUR)", f["won_revenue_eur"], "sum of won amounts (revenue ≠ pipeline)", None),
            ("Cost per meeting (EUR)", f["cost_per_meeting_eur"], "enrichment cost / meetings booked", None)]
    for name, val, d, ci in rows:
        L.append(f"| {name} | {val} | {d} | {ci if ci else ''} |")
    for title, key, cols in (("By sector", "by_sector", ("sector", "n", "meetings", "meetings_per_worked_account")),
                             ("By offer", "by_offer", ("offer_id", "n", "meetings", "meetings_per_worked_account")),
                             ("By source", "by_source", ("source", "n", "connect_rate", "cost_per_meeting_eur")),
                             ("Objections", "objections", ("objection", "n")), ("Loss reasons", "loss_reasons", ("loss_reason", "n"))):
        L += ["", f"## {title}", "", "| " + " | ".join(cols) + " | sample |", "|" + "---|" * (len(cols) + 1)]
        for r in k[key]:
            flag = "⚠️ small (<30)" if r.get("n", MIN_SAMPLE) < MIN_SAMPLE else "ok"
            L.append("| " + " | ".join(str(r[c]) for c in cols) + f" | {flag} |")
    L += ["", "## Proposed experiments (no automatic rule change)", ""]
    for h in hyps:
        L += [f"- **Observation**: {h['observation']}" + (f" ({h['overlap']})" if "overlap" in h else ""),
              f"  - Experiment: {h['experiment']}", f"  - Rule change: {h['rule_change']}"]
    L += ["", f"_Rows analysed: {n}. Rep-level figures are context for coaching and allocation, never a ranking of people._"]
    return "\n".join(L)


def main(argv: list[str]) -> int:
    src = Path(argv[1]) if len(argv) > 1 and not argv[1].startswith("--") else ROOT / "data" / "synthetic" / "outcomes-500.json"
    db_path = Path(argv[argv.index("--db") + 1]) if "--db" in argv else ROOT / "outputs" / "analytics" / "rubicon.db"
    db_path.parent.mkdir(parents=True, exist_ok=True)
    with sqlite3.connect(db_path) as db:
        n = load(db, src)
        k = run_kpis(db)
        simulated = db.execute("SELECT MIN(simulated) FROM campaign_outcomes").fetchone()[0] == 1
    hyps = hypotheses(k)
    out = db_path.parent
    (out / "kpi-report.md").write_text(report(n, k, hyps, simulated), encoding="utf-8")
    (out / "kpis.json").write_text(json.dumps({"simulated": simulated, "kpis": k, "hypotheses": hyps}, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"rows {n} · simulated={simulated} · report {out / 'kpi-report.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
